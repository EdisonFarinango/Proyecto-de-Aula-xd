    private void actualizarTallasSeleccionadas() {
        String tallaSeleccionada = (String) cmbTallas.getSelectedItem();
        String[] tallasArray = txtTallasSeleccionadas.getText().split(",\\s*");

        // Verificar si la talla ya está en el texto
        boolean yaSeleccionada = false;
        for (String talla : tallasArray) {
            if (talla.equals(tallaSeleccionada)) {
                yaSeleccionada = true;
                break;
            }
        }

        if (!yaSeleccionada) {
            String tallasTextoActual = txtTallasSeleccionadas.getText();
            if (tallasTextoActual.isEmpty()) {
                txtTallasSeleccionadas.setText(tallaSeleccionada);
            } else {
                txtTallasSeleccionadas.setText(tallasTextoActual + ", " + tallaSeleccionada);
            }
        }
    }

    private void insertarProducto() {
        String nombreProducto = txtNombreProducto.getText();
        String categoria = (String) cmbCategoria.getSelectedItem();
        String tallasTexto = txtTallasSeleccionadas.getText();
        String preciosTexto = txtPreciosSeleccionados.getText();
        String stockTexto = txtStockSeleccionado.getText();
        String rutaImagen = txtRutaImagen.getText();
        String carpetaDestino = txtCarpetaDestino.getText();

        if (nombreProducto.isEmpty() || categoria == null || tallasTexto.isEmpty() || preciosTexto.isEmpty() || stockTexto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, complete todos los campos.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String[] tallasArray = tallasTexto.split(",\\s*");
        String[] preciosArray = preciosTexto.split(",\\s*");
        String[] stockArray = stockTexto.split(",\\s*");

        if (tallasArray.length != preciosArray.length || tallasArray.length != stockArray.length) {
            JOptionPane.showMessageDialog(this, "El número de tallas, precios y stock no coincide.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Convertir arrays a textos separados por comas
        String tallasTextoSQL = String.join(",", tallasArray);
        String preciosTextoSQL = String.join(",", preciosArray);
        String stockTextoSQL = String.join(",", stockArray);

        ConexionBD conexion = new ConexionBD();
        Connection conn = conexion.conn;

        try {
            if (conn != null) {
                conn.setAutoCommit(false);

                // Llamar al procedimiento almacenado
                String callProcedureSQL = "{CALL InsertarProductoConTallasYPrecios(?, ?, ?, ?, ?)}";
                try (PreparedStatement cstmt = conn.prepareCall(callProcedureSQL)) {
                    cstmt.setString(1, nombreProducto);
                    cstmt.setString(2, categoria);
                    cstmt.setString(3, tallasTextoSQL);
                    cstmt.setString(4, stockTextoSQL);
                    cstmt.setString(5, preciosTextoSQL);
                    cstmt.execute();
                }

                conn.commit();
                JOptionPane.showMessageDialog(this, "Producto insertado correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);

                // Mover imagen a la carpeta de destino
                if (rutaImagen != null && !rutaImagen.isEmpty()) {
                    File archivoImagen = new File(rutaImagen);
                    if (archivoImagen.exists()) {
                        File destino = new File(carpetaDestino, archivoImagen.getName());
                        try {
                            Files.copy(archivoImagen.toPath(), destino.toPath(), StandardCopyOption.REPLACE_EXISTING);
                            JOptionPane.showMessageDialog(this, "Imagen guardada con éxito en " + destino.getAbsolutePath(), "Éxito", JOptionPane.INFORMATION_MESSAGE);
                        } catch (IOException ioEx) {
                            JOptionPane.showMessageDialog(this, "Error al guardar la imagen: " + ioEx.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                            ioEx.printStackTrace();
                        }
                    } else {
                        JOptionPane.showMessageDialog(this, "El archivo de imagen seleccionado no existe.", "Advertencia", JOptionPane.WARNING_MESSAGE);
                    }
                }
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error al conectar a la base de datos: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            conexion.desconectar();
        }
    }


