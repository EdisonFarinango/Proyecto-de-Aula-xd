    private void agregarStock() {
        Integer stock = (Integer) spnStock.getValue();
        String tallaSeleccionada = (String) cmbTallas.getSelectedItem();

        if (tallaSeleccionada == null) {
            JOptionPane.showMessageDialog(this, "Seleccione una talla para agregar el stock.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Verificar que el stock no sea negativo
        if (stock < 0) {
            JOptionPane.showMessageDialog(this, "El stock no puede ser negativo.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Verificar que el stock se ingrese para la talla seleccionada
        tallaStockMap.put(tallaSeleccionada, stock);

        // Actualizar el JTextField de stock seleccionado
        actualizarStockSeleccionado();

        // Limpiar el JSpinner
        spnStock.setValue(0);
    }

    private void actualizarStockSeleccionado() {
        StringBuilder stockBuilder = new StringBuilder();

        // Agregar el stock en el orden que fueron seleccionados
        for (String talla : txtTallasSeleccionadas.getText().split(",\\s*")) {
            Integer stock = tallaStockMap.get(talla);
            if (stock != null) {
                stockBuilder.append(stock).append(", ");
            }
        }

        // Eliminar la última coma y espacio
        if (stockBuilder.length() > 0) {
            stockBuilder.setLength(stockBuilder.length() - 2);
        }

        txtStockSeleccionado.setText(stockBuilder.toString());
    }

    private void agregarPrecio() {
        String precioTexto = txtPrecio.getText();
        String tallaSeleccionada = (String) cmbTallas.getSelectedItem();

        if (tallaSeleccionada == null) {
            JOptionPane.showMessageDialog(this, "Seleccione una talla para agregar el precio.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double precio = Double.parseDouble(precioTexto);

            // Verificar que el precio se ingrese para la talla seleccionada
            tallaPrecioMap.put(tallaSeleccionada, precio);

            // Actualizar el JTextField de precios seleccionados
            actualizarPreciosSeleccionados();

            // Limpiar el campo de precio
            txtPrecio.setText("");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El precio ingresado no es válido.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void actualizarPreciosSeleccionados() {
        StringBuilder preciosBuilder = new StringBuilder();

        // Agregar los precios en el orden que fueron seleccionados
        for (String talla : txtTallasSeleccionadas.getText().split(",\\s*")) {
            Double precio = tallaPrecioMap.get(talla);
            if (precio != null) {
                preciosBuilder.append(precio).append(", ");
            }
        }

        // Eliminar la última coma y espacio
        if (preciosBuilder.length() > 0) {
            preciosBuilder.setLength(preciosBuilder.length() - 2);
        }

        txtPreciosSeleccionados.setText(preciosBuilder.toString());
    }

   private void seleccionarImagen() {
    JFileChooser fileChooser = new JFileChooser();
    int resultado = fileChooser.showOpenDialog(this);
    if (resultado == JFileChooser.APPROVE_OPTION) {
        archivoImagen = fileChooser.getSelectedFile();
        String productName = txtNombreProducto.getText().replace(' ', '_');
        String newImageName = productName + "." + archivoImagen.getName().substring(archivoImagen.getName().lastIndexOf('.') + 1);
        File newImageFile = new File(archivoImagen.getParent(), newImageName);
        archivoImagen.renameTo(newImageFile);
        txtRutaImagen.setText(newImageFile.getAbsolutePath());

        // Mostrar la imagen en el JLabel
        try {
            ImageIcon imageIcon = new ImageIcon(newImageFile.getAbsolutePath());
            Image image = imageIcon.getImage().getScaledInstance(lblImagen.getWidth(), lblImagen.getHeight(), Image.SCALE_SMOOTH);
            lblImagen.setIcon(new ImageIcon(image));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar la imagen: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
}

