    // Método para cargar categorías en el JComboBox
    private void cargarCategorias() {
        Connection connection = null;
        PreparedStatement stmt = null;
        ResultSet rs = null;

        try {
            connection = conexionBD.conn; // Obtén la conexión desde ConexionBD
            stmt = connection.prepareStatement("SELECT cat_nombre FROM categorias");
            rs = stmt.executeQuery();

            while (rs.next()) {
                cmbCategoria.addItem(rs.getString("cat_nombre"));
            }

        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error al cargar categorías: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            // Cierra los recursos sin cerrar la conexión
            try {
                if (rs != null) {
                    rs.close();
                }
                if (stmt != null) {
                    stmt.close();
                }
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
    }

    private void cargarTallas() {
        Connection connection = null;
        PreparedStatement stmt = null;
        ResultSet rs = null;

        try {
            connection = conexionBD.conn; // Obtén la conexión desde ConexionBD
            stmt = connection.prepareStatement("SELECT talla_nombre FROM tallas");
            rs = stmt.executeQuery();

            while (rs.next()) {
                cmbTallas.addItem(rs.getString("talla_nombre"));
            }

        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error al cargar tallas: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            // Cierra los recursos sin cerrar la conexión
            try {
                if (rs != null) {
                    rs.close();
                }
                if (stmt != null) {
                    stmt.close();
                }
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
    }

