    private void setFechaActual() {
        // Obtén la fecha actual
        LocalDate fechaActual = LocalDate.now();
        // Define el formato de la fecha
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy");
        // Establece la fecha en el campo
        fieldFechaPed.setText(fechaActual.format(formatter));
    }

    public void setDatosFactura(DefaultTableModel modeloCarrito, int[] indicesColumnas, String[] nombresColumnas) {
        DefaultTableModel modeloFactura = (DefaultTableModel) tablaFactura.getModel();

        // Limpiar datos anteriores
        modeloFactura.setRowCount(0);

        // Establecer nombres de columnas
        modeloFactura.setColumnIdentifiers(nombresColumnas);

        for (int i = 0; i < modeloCarrito.getRowCount(); i++) {
            Object[] rowData = new Object[indicesColumnas.length];
            for (int j = 0; j < indicesColumnas.length; j++) {
                rowData[j] = modeloCarrito.getValueAt(i, indicesColumnas[j]);
            }
            modeloFactura.addRow(rowData);
        }
    }

