    private void cargarClientes() {
        DefaultTableModel modelo = (DefaultTableModel) TablaTotalClientes.getModel();
        modelo.setRowCount(0); // Limpiar la tabla antes de agregar nuevos datos

        String sp = "{CALL sp_obtenerClientes()}"; // Llamada al Stored Procedure

        try (CallableStatement cs = conexion.conn.prepareCall(sp); ResultSet rs = cs.executeQuery()) {

            while (rs.next()) {
                Object[] row = {
                    rs.getString("nombre"),
                    rs.getString("apellido"),
                    rs.getString("cedula"),
                    rs.getString("correo")
                };
                modelo.addRow(row);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al obtener los datos: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }

    private void llenarTablaClientes(java.sql.Date fechaInicio, java.sql.Date fechaFin) {
        DefaultTableModel modelo = (DefaultTableModel) tablaListaClientes.getModel();
        modelo.setRowCount(0); // Limpiar la tabla antes de agregar nuevos datos

        String sp = "{CALL sp_obtenerClientesPorFechas(?, ?)}"; // Llamada al Stored Procedure

        try (CallableStatement cs = conexion.conn.prepareCall(sp)) {
            cs.setDate(1, fechaInicio);
            cs.setDate(2, fechaFin);

            try (ResultSet rs = cs.executeQuery()) {
                while (rs.next()) {
                    String nombre = rs.getString("nombre");
                    String apellido = rs.getString("apellido");
                    String cedula = rs.getString("cedula");
                    int vecesQueHaEntrado = rs.getInt("veces_que_ha_entrado");

                    // Agregar los datos a la tabla
                    modelo.addRow(new Object[]{nombre, apellido, cedula, vecesQueHaEntrado});

                    // Imprimir en consola
                    System.out.println("Nombre: " + nombre);
                    System.out.println("Apellido: " + apellido);
                    System.out.println("Cédula: " + cedula);
                    System.out.println("Veces que ha entrado: " + vecesQueHaEntrado);
                    System.out.println("---------------------------");
                }
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al obtener los datos: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }

