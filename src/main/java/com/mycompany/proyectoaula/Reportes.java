    private void btnListarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnListarMouseClicked
        // Obtiene las fechas de los JDateChooser
        java.util.Date fechaInicio = fechaMin.getDate();
        java.util.Date fechaFin = fechaMax.getDate();
        java.util.Date fechaActualDate = new java.util.Date(); // Fecha actual

        // Verifica que las fechas no sean nulas
        if (fechaInicio == null || fechaFin == null) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione ambas fechas.");
            return;
        }

        // Verifica que la fecha de inicio no sea después de la fecha de fin
        if (fechaInicio.after(fechaFin)) {
            JOptionPane.showMessageDialog(this, "La fecha de inicio no puede ser después de la fecha de fin.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Verifica que las fechas no superen la fecha actual
        if (fechaInicio.after(fechaActualDate) || fechaFin.after(fechaActualDate)) {
            JOptionPane.showMessageDialog(this, "Las fechas no pueden ser posteriores a la fecha actual.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Formatea las fechas a String en formato yyyy-MM-dd
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String fechaInicioStr = sdf.format(fechaInicio);
        String fechaFinStr = sdf.format(fechaFin);

        // Conecta a la base de datos
        ConexionBD conexion = new ConexionBD();
        conexion.conectar();

        try {
            // Llama al Stored Procedure para obtener las facturas en el intervalo de fechas
            String sp = "{CALL sp_obtenerFacturasPorFechas(?, ?)}";
            CallableStatement cs = conexion.conn.prepareCall(sp);
            cs.setString(1, fechaInicioStr);
            cs.setString(2, fechaFinStr);

            // Ejecuta el SP y obtiene los resultados
            ResultSet rs = cs.executeQuery();

            // Configura el modelo de la tabla
            DefaultTableModel model = new DefaultTableModel();
            model.addColumn("ID Factura");
            model.addColumn("Cédula del Usuario");
            model.addColumn("Total");
            model.addColumn("IVA");
            model.addColumn("Fecha");
            model.addColumn("Método de Pago");
            model.addColumn("Subtotal");

            // Llena la tabla con los datos obtenidos
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("ID Factura"),
                    rs.getString("Cédula del Usuario"),
                    rs.getDouble("Total"),
                    rs.getDouble("IVA"),
                    rs.getDate("Fecha"),
                    rs.getInt("Método de Pago"),
                    rs.getDouble("Subtotal")
                });
            }

            tablaListaFacturas.setModel(model);
            btnImprimir.setEnabled(true);
            rs.close();
            cs.close();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error al consultar las facturas: " + ex.getMessage());
            ex.printStackTrace();
        } finally {
            conexion.desconectar();
        }
    }//GEN-LAST:event_btnListarMouseClicked

    private void btnCalcularGananciasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularGananciasActionPerformed

        // Obtiene las fechas de los JDateChooser
        java.util.Date fechaInicio = fechaMin.getDate();
        java.util.Date fechaFin = fechaMax.getDate();

        // Verifica que las fechas no sean nulas
        if (fechaInicio == null || fechaFin == null) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione ambas fechas.");
            return;
        }

        // Formatea las fechas a String en formato yyyy-MM-dd
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String fechaInicioStr = sdf.format(fechaInicio);
        String fechaFinStr = sdf.format(fechaFin);

        // Conecta a la base de datos
        ConexionBD conexion = new ConexionBD();
        conexion.conectar();

        try {
            // Llama a la función TotalVentasEnPeriodo
            String sql = "{ ? = CALL TotalVentasEnPeriodo(?, ?) }";
            CallableStatement cs = conexion.conn.prepareCall(sql);
            cs.registerOutParameter(1, Types.DOUBLE);
            cs.setString(2, fechaInicioStr);
            cs.setString(3, fechaFinStr);

            // Ejecuta la llamada a la función
            cs.execute();

            // Obtiene el resultado
            double totalGanancias = cs.getDouble(1);

            // Formatea el resultado a dos decimales
            DecimalFormat df = new DecimalFormat("#.00");
            String totalGananciasFormateado = df.format(totalGanancias);

            // Muestra el resultado en un JOptionPane
            fieldTotalGanancias.setText("Total de Ventas: " + totalGananciasFormateado);

            cs.close();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error al calcular las ganancias: " + ex.getMessage());
            ex.printStackTrace();
        } finally {
            conexion.desconectar();
        }


    }//GEN-LAST:event_btnCalcularGananciasActionPerformed

